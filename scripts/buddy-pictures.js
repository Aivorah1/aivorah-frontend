// Turns the Learning Buddy picture library into app images.
//
//   npm i --no-save sharp
//   node scripts/buddy-pictures.js <path to learning-buddy repo>/characters
//
// Source layout: <character>/<outfit>-<emotion>.png (and _base-casual-happy.png for casual clothes).
// Writes 512px WebP files to assets/learning-buddies/v2/<character>/ and regenerates
// src/screens/student/profile/buddyPictures.generated.ts (Metro needs a static require per image).
// Safe to re-run whenever new outfits or emotions are added: the app shows whatever pictures exist.
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const SRC = process.argv[2];
if (!SRC || !fs.existsSync(SRC)) {
  console.error('usage: node scripts/buddy-pictures.js <learning-buddy>/characters');
  process.exit(1);
}
const ROOT = path.resolve(process.argv[1], '..', '..'); // the repo root (this file is in scripts/)
const OUT = path.join(ROOT, 'assets', 'learning-buddies', 'v2');
const MAP = path.join(ROOT, 'src', 'screens', 'student', 'profile', 'buddyPictures.generated.ts');
const NAME = /^(?:_base-)?([a-z]+)-([a-z]+)\.(png|jpe?g|webp)$/i;

(async () => {
  const entries = [];
  for (const character of fs.readdirSync(SRC).sort()) {
    const dir = path.join(SRC, character);
    if (!/^[a-z]+$/.test(character) || !fs.statSync(dir).isDirectory()) continue;
    for (const file of fs.readdirSync(dir).sort()) {
      const m = NAME.exec(file);
      if (!m) { console.warn(`skipped ${character}/${file} (name should be <outfit>-<emotion>.png)`); continue; }
      const key = `${m[1].toLowerCase()}-${m[2].toLowerCase()}`;
      const target = path.join(OUT, character, `${key}.webp`);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      await sharp(path.join(dir, file)).resize(512, 512, { fit: 'cover' }).webp({ quality: 80 }).toFile(target);
      entries.push([character, key]);
    }
  }
  const byChar = {};
  for (const [c, k] of entries) (byChar[c] ||= []).push(k);
  const lines = [
    '// GENERATED by scripts/buddy-pictures.js. Do not edit by hand; re-run the script instead.',
    '// Learning Buddy pictures: character -> "<outfit>-<emotion>" -> image.',
    'export const BUDDY_PICTURES: Record<string, Record<string, any>> = {',
    ...Object.entries(byChar).flatMap(([c, keys]) => [
      `  ${c}: {`,
      ...keys.map((k) => `    '${k}': require('../../../../assets/learning-buddies/v2/${c}/${k}.webp'),`),
      '  },',
    ]),
    '};',
    '',
  ];
  fs.writeFileSync(MAP, lines.join('\n'));
  console.log(`wrote ${entries.length} pictures for ${Object.keys(byChar).length} characters`);
})().catch((e) => { console.error(e); process.exit(1); });
